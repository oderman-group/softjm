-- Grupo 3 (clasificación). catp_grupo = 3.
-- catp_cod_grupo guarda el código Ofima, con ceros a la izquierda.
-- VARIOS queda con código 0. Los de la lista quedan habilitados.
-- El resto del grupo 3 de la empresa queda deshabilitado.

SET @id_empresa = 1;

UPDATE productos_categorias
SET catp_habilitada = 0
WHERE catp_grupo = 3
  AND catp_id_empresa = @id_empresa;

UPDATE productos_categorias
SET catp_habilitada = 1,
    catp_cod_grupo = CASE CONVERT(catp_nombre USING utf8mb4)
        WHEN 'VARIOS' THEN '0'
        WHEN 'ESTACIONES TOTALES' THEN '001'
        WHEN 'RECEPTOR GNSS - GPS' THEN '002'
        WHEN 'NIVELES' THEN '003'
        WHEN 'ACCESORIOS ESTA-NIVEL-TEO-GNSS' THEN '004'
        WHEN 'GEORRADARES' THEN '005'
        WHEN 'LIDAR SLAM ESCANER' THEN '006'
        WHEN 'COLECTORES Y TABLETS' THEN '007'
        WHEN 'BATERIAS Y CARGADORES TOPOGRAFIA' THEN '008'
        WHEN 'DRONES' THEN '009'
        WHEN 'ACCESORIOS DRONES' THEN '010'
        WHEN 'BATERÍAS Y CARGADORES DRONES' THEN '011'
        WHEN 'REPUESTOS TOPOGRAFIA' THEN '012'
        WHEN 'REPUESTOS GEORRADAR' THEN '013'
        WHEN 'REPUESTOS DRONE AGRAS' THEN '014'
        WHEN 'REPUESTOS DRONE ENTERPRISE' THEN '015'
        WHEN 'REPUESTOS DRONE CONSUMO' THEN '016'
        WHEN 'ESTUCHES Y MORRALES' THEN '017'
        WHEN 'HERRAMIENTAS Y MUEBLES' THEN '018'
        WHEN 'SOFTWARE' THEN '019'
        WHEN 'ENERGIA PORTATIL' THEN '020'
        WHEN 'EQUIPO DE COMPUTO' THEN '021'
        WHEN 'CAMARAS' THEN '022'
        WHEN 'RELOJES' THEN '023'
        WHEN 'AUDIFONOS' THEN '024'
        WHEN 'SERVICIO DE ALQUILER' THEN '025'
        WHEN 'SERVICIO DE CAPACITACION' THEN '026'
        WHEN 'SERVICIO PRO INGENIERIA Y TOPO' THEN '027'
        WHEN 'SERVICIO TECNICO' THEN '028'
        WHEN 'TERMOMETROS' THEN '029'
        WHEN 'TEODOLITOS' THEN '030'
        WHEN 'GENERADORES PLANTA ELECTRICA PORTABLE' THEN '031'
        WHEN 'DISTANCIOMETROS' THEN '032'
        WHEN 'ESCANER LIDAR TERRESTRE' THEN '033'
        WHEN 'LOCALIZADOR DE TUBERIA' THEN '034'
    END
WHERE catp_grupo = 3
  AND catp_id_empresa = @id_empresa
  AND CONVERT(catp_nombre USING utf8mb4) IN (
    'VARIOS',
    'ESTACIONES TOTALES',
    'RECEPTOR GNSS - GPS',
    'NIVELES',
    'ACCESORIOS ESTA-NIVEL-TEO-GNSS',
    'GEORRADARES',
