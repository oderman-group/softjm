    'BATERIAS Y CARGADORES TOPOGRAFIA',
    'DRONES',
    'ACCESORIOS DRONES',
    'BATERÍAS Y CARGADORES DRONES',
    'REPUESTOS TOPOGRAFIA',
    'REPUESTOS GEORRADAR',
    'REPUESTOS DRONE AGRAS',
    'REPUESTOS DRONE ENTERPRISE',
    'REPUESTOS DRONE CONSUMO',
    'ESTUCHES Y MORRALES',
